-- Esquema inicial, conforme o diagrama de classes (docs/03-modelagem).
-- Tabelas de módulos diferentes não têm chave estrangeira entre si: um módulo
-- referencia o outro apenas pelo id.

-- Módulo identidade
create table usuario (
    id      uuid primary key,
    nome    varchar(120) not null,
    email   varchar(254) not null unique,
    perfil  varchar(20)  not null check (perfil in ('COLABORADOR', 'CURADOR', 'ADMINISTRADOR'))
);

-- Módulo dicionario
create table regiao (
    id    bigint generated by default as identity primary key,
    uf    varchar(2)  not null,
    nome  varchar(60) not null
);

create table configuracao_mao (
    id      bigint generated by default as identity primary key,
    codigo  varchar(10)  not null unique,
    imagem  varchar(255)
);

create table assunto (
    id    bigint generated by default as identity primary key,
    nome  varchar(60) not null unique
);

create table verbete (
    id                 uuid primary key,
    palavra            varchar(120)  not null,
    acepcao            varchar(1000) not null,
    exemplo            varchar(500),
    exemplo_libras     varchar(500),
    classe_gramatical  varchar(40),
    origem             varchar(120),
    assunto_id         bigint not null references assunto (id)
);
create index idx_verbete_palavra on verbete (lower(palavra));

create table sinal (
    id                   uuid primary key,
    padrao               boolean not null,
    publicado            boolean not null,
    verbete_id           uuid    not null references verbete (id) on delete cascade,
    regiao_id            bigint  references regiao (id),
    configuracao_mao_id  bigint  not null references configuracao_mao (id),
    video_id             uuid    not null
);
create index idx_sinal_verbete on sinal (verbete_id);

-- Módulo midia
create table video (
    id               uuid primary key,
    url              varchar(255)     not null unique,
    formato          varchar(10)      not null,
    duracao_seg      integer          not null,
    tamanho_mb       double precision not null,
    transcodificado  boolean          not null
);

-- Módulo privacidade
create table consentimento (
    id                 uuid primary key,
    versao_termo       varchar(20) not null,
    data_hora          timestamp with time zone not null,
    sinalizante_menor  boolean not null,
    termo_responsavel  varchar(255),
    revogado_em        timestamp with time zone
);

-- Módulo submissoes
create table submissao (
    id                uuid primary key,
    autor_id          uuid not null,
    curador_id        uuid,
    consentimento_id  uuid not null,
    sinal_id          uuid not null unique,
    data_envio        timestamp with time zone,
    status            varchar(20) not null
        check (status in ('EM_ANALISE', 'AJUSTE_SOLICITADO', 'APROVADA', 'REJEITADA')),
    justificativa     varchar(1000)
);
create index idx_submissao_status on submissao (status, data_envio);
create index idx_submissao_autor on submissao (autor_id);
